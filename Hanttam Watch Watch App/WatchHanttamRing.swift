    static func path(in rect: CGRect) -> CGPath {
        let fitted = aspectFitRect(for: viewBox, in: rect)
        let path = CGMutablePath()

        for contour in contours {
            guard let first = contour.first else { continue }
            path.move(to: scaled(first, in: fitted))

            for point in contour.dropFirst() {
                path.addLine(to: scaled(point, in: fitted))
            }

            path.closeSubpath()
        }

        return path
    }

    private static func scaled(_ point: CGPoint, in rect: CGRect) -> CGPoint {
        CGPoint(
            x: rect.minX + point.x * rect.width,
            y: rect.minY + point.y * rect.height
        )
    }

    private static func aspectFitRect(for size: CGSize, in rect: CGRect) -> CGRect {
        let scale = min(rect.width / size.width, rect.height / size.height)
        let width = size.width * scale
        let height = size.height * scale

        return CGRect(
            x: rect.midX - width / 2,
            y: rect.midY - height / 2,
            width: width,
            height: height
        )
    }
